void gui_init(void *fb, u32 width, u32 height, u32 bpp)
{
    gui_disp.fb = fb;
    gui_disp.width = width;
    gui_disp.height = height;
    gui_disp.bpp = bpp;
    gui_disp.stride = width * (bpp / 8);
}

void gui_draw_pixel(u32 x, u32 y, color_t c)
{
    if (x >= gui_disp.width || y >= gui_disp.height)
        return;
    if (!gui_disp.fb)
        return;
    volatile u8 *fb = (volatile u8 *)gui_disp.fb;
    u32 off = y * gui_disp.stride + x * (gui_disp.bpp / 8);
    if (gui_disp.bpp == 16) {
        fb[off]     = (u8)(c & 0xFF);
        fb[off + 1] = (u8)(c >> 8);
    }
}

void gui_draw_line(u32 x0, u32 y0, u32 x1, u32 y1, color_t c)
{
    s32 dx = (s32)(x1 - x0);
    s32 dy = (s32)(y1 - y0);
    s32 sx = dx >= 0 ? 1 : -1;
    s32 sy = dy >= 0 ? 1 : -1;
    dx = dx < 0 ? -dx : dx;
    dy = dy < 0 ? -dy : dy;
    s32 err = (dx > dy ? dx : -dy) / 2;

    for (;;) {
        gui_draw_pixel(x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        s32 e2 = err;
        if (e2 > -dx) { err -= dy; x0 += sx; }
        if (e2 < dy)  { err += dx; y0 += sy; }
    }
}

